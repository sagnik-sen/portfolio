// Malformed art fails at module load instead of rendering skewed.
for (const [name, rows] of Object.entries(ICONS)) {
  if (rows.length !== 12 || rows.some((row) => row.length !== 12)) throw new Error(`PixelIcon "${name}" is not 12x12`);
}

const BASE = "inline-block h-[0.9em] w-[0.9em] align-[-0.05em]";

export function PixelIcon({ name, className }: { name: IconName; className?: string }) {
  return (
    <svg
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden
      className={className ? `${BASE} ${className}` : BASE}
    >
      {ICONS[name].flatMap((row, y) =>
        [...row.matchAll(/#+/g)].map((run) => (
          <rect key={`${y}-${run.index}`} x={run.index} y={y} width={run[0].length} height={1} />
        )),
      )}
    </svg>
  );
}
